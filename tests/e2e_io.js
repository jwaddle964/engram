const { chromium, devices } = require('playwright');
const SHOTS = process.env.SHOTS, APKG = process.env.APKG;
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['iPhone 13'] });
  const page = await ctx.newPage();
  const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto('http://localhost:8765/');
  await page.waitForSelector('.deck-list');
  await page.evaluate(() => Samples.load());
  await page.waitForTimeout(400);
  // study the sample IO note via cram
  const ids = await page.evaluate(() => Col.searchCards('note:"Image Occlusion"').map((c) => c.id).sort((a, b) => DB.col.cards.get(a).ord - DB.col.cards.get(b).ord));
  console.log('IO sample cards:', ids.length);
  assert(ids.length === 4, '4 IO cards');
  await page.evaluate((ids) => { window.__cram = { title: 'IO', ids: ids.slice(0, 2), did: 1 }; }, ids);
  await page.goto('http://localhost:8765/#/cram');
  await page.waitForSelector('.study .show');
  await page.waitForTimeout(400);
  const shapesQ = await page.evaluate(() => { const sr = document.querySelector('.card-host').shadowRoot; return { svg: !!sr.querySelector('.io-overlay'), n: sr.querySelectorAll('.io-overlay rect').length, imgLoaded: sr.querySelector('#image-occlusion-container img').naturalWidth }; });
  console.log('question side:', JSON.stringify(shapesQ));
  assert(shapesQ.svg && shapesQ.n === 4 && shapesQ.imgLoaded > 0, 'masks drawn over loaded image');
  await page.screenshot({ path: SHOTS + '/70-io-q.png' });
  await page.click('.study .show');
  await page.waitForTimeout(300);
  await page.screenshot({ path: SHOTS + '/71-io-a.png' });
  await page.evaluate(() => document.querySelector('.card-host').shadowRoot.querySelector('#toggle').click());
  await page.waitForTimeout(100);
  await page.screenshot({ path: SHOTS + '/72-io-a-toggled.png' });

  // ---- create an IO note in the editor with touch-like drags
  await page.goto('http://localhost:8765/#/add');
  await page.waitForSelector('select[aria-label="Note type"]');
  await page.selectOption('select[aria-label="Note type"]', { label: 'Image Occlusion' });
  await page.waitForSelector('.io-pick');
  await page.screenshot({ path: SHOTS + '/73-io-add-empty.png' });
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.click('.io-pick')]);
  await chooser.setFiles(require('path').join(APKG, 'diagram.png'));
  await page.waitForSelector('.io-stage img[src^="blob:"]');
  await page.waitForTimeout(300);
  const box = await page.$eval('.io-edit-overlay', (e) => { const b = e.getBoundingClientRect(); return { x: b.x, y: b.y, w: b.width, h: b.height }; });
  const drag = async (x1, y1, x2, y2) => { await page.mouse.move(box.x + x1 * box.w, box.y + y1 * box.h); await page.mouse.down(); await page.mouse.move(box.x + (x1 + x2) / 2 * box.w, box.y + (y1 + y2) / 2 * box.h); await page.mouse.move(box.x + x2 * box.w, box.y + y2 * box.h); await page.mouse.up(); };
  await drag(0.05, 0.1, 0.35, 0.3);
  await drag(0.6, 0.5, 0.9, 0.8);
  await drag(0.6, 0.1, 0.9, 0.3);
  // tap boxes 2 and 3, group them
  await page.mouse.click(box.x + 0.75 * box.w, box.y + 0.65 * box.h);
  await page.mouse.click(box.x + 0.75 * box.w, box.y + 0.2 * box.h);
  await page.click('button[title^="Selected boxes become one card"]');
  await page.fill('.io-editor textarea >> nth=0', 'Test header');
  const info = await page.textContent('.io-editor .muted.small');
  console.log('editor info:', info);
  await page.screenshot({ path: SHOTS + '/74-io-editor.png' });
  await page.click('.sticky-bottom >> text=Add');
  await page.waitForTimeout(300);
  const toast = await page.textContent('.toast');
  console.log('toast:', toast);
  const note = await page.evaluate(() => { const n = Array.from(DB.col.notes.values()).pop(); return { f0: n.fields[0], f1: n.fields[1], f2: n.fields[2], cards: Col.cardsOfNote(n.id).map((c) => c.ord) }; });
  console.log('saved occlusion:', note.f0);
  console.log('image field:', note.f1, '| header:', note.f2, '| card ords:', JSON.stringify(note.cards));
  assert(note.cards.length === 2, 'grouped -> 2 cards');
  // edit it again: masks must load back
  const nid = await page.evaluate(() => Array.from(DB.col.notes.values()).pop().id);
  await page.goto('http://localhost:8765/#/edit/' + nid);
  await page.waitForSelector('.io-stage img[src^="blob:"]');
  await page.waitForTimeout(200);
  const nrects = await page.$$eval('.io-edit-overlay rect', (r) => r.length);
  console.log('edit view rects:', nrects);
  assert(nrects === 3, 'masks restored in editor');
  // ---- import the real Anki IO package and render it
  await page.goto('http://localhost:8765/#/import');
  const [ch2] = await Promise.all([page.waitForEvent('filechooser'), page.click('text=Choose file')]);
  await ch2.setFiles(require('path').join(APKG, 'io.apkg'));
  await page.waitForSelector('.sheet >> text=Media files');
  await page.click('.sheet >> button:has-text("Import")');
  await page.waitForSelector('.sheet >> text=Imported');
  const ntCount = await page.evaluate(() => Array.from(DB.col.notetypes.values()).filter((n) => n.name.startsWith('Image Occlusion')).length);
  console.log('IO notetypes after import (1 = matched stock):', ntCount);
  const aid = await page.evaluate(() => Col.searchCards('"Label the parts"').map((c) => c.id));
  await page.evaluate((ids) => { window.__cram = { title: 'Anki IO', ids: ids.slice(0, 1).concat(ids.slice(1, 2)), did: 1 }; }, aid.sort());
  await page.goto('http://localhost:8765/#/');
  await page.goto('http://localhost:8765/#/cram');
  await page.waitForSelector('.study .show');
  await page.waitForTimeout(400);
  const shapesA = await page.evaluate(() => { const sr = document.querySelector('.card-host').shadowRoot; return Array.from(sr.querySelectorAll('.io-overlay *')).map((e) => e.tagName + ':' + (e.getAttribute('fill') || '')); });
  console.log('anki IO shapes:', shapesA.join(' '));
  await page.screenshot({ path: SHOTS + '/75-anki-io-q.png' });
  console.log('ERRORS:', errs.length ? errs : 'none');
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
